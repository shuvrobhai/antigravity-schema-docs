#!/usr/bin/env python3
"""Archive cited sources from reference/19-works-cited.md into evidence/sources/.

For each citation in the Works Cited module (section 19), fetch the page and
store a readable Markdown snapshot at:

    evidence/sources/<category>/NN-slug.md

where NN is the citation number from section 19 (the filename is a citation
pointer back to the works-cited list) and <category> mirrors the source tag
(docs | google | protocol | community).

Each file carries a YAML-style header recording provenance: citation number,
title, URL, fetch date, and HTTP status. After every run the script
regenerates evidence/sources/index.md — the archive manifest — so the index
can never drift from the files (same contract as scripts/build.py --check).

Dedup rule: when two citations share a URL (e.g. #2 and #62 both point at the
CLI Reference page), the page is archived once under the lowest number and the
higher citation is recorded in the manifest as a duplicate.

Dependencies: python3 stdlib + pandoc (HTML -> Markdown conversion).

Usage:
  fetch_sources.py                       fetch every citation in section 19
  fetch_sources.py --category docs       fetch only [DOCS] citations
  fetch_sources.py --category docs --category google
  fetch_sources.py --force               re-fetch even when the file exists
  fetch_sources.py --check               exit 0 if the archive is in sync, 1 if not
  fetch_sources.py --insecure            disable SSL certificate verification (debug only)
"""
