# "1. Hooks — https://antigravity.google/docs/hooks"
# URL capture stops at the first whitespace so trailing notes survive, e.g.
# "35. Configuration — https://.../configuration/ (relocated; ...)".
LIST_ITEM = re.compile(r"^(\d+)\. (.+?) — (https?://\S+?)(?=\s|$)")
# "| 53 | `[DOCS]` | /agents Panel Documentation | https://... |"
TABLE_ROW = re.compile(r"^\| (\d+) \| `?\[([A-Z0-9-]+)\]`? \| (.+?) \| (https?://\S+) \|$")
FRONT = re.compile(r"^---\n(.*?)\n---\n", re.S)


